/** id로 페르소나 템플릿을 조회합니다. */
export function getPersonaById(id: string): PersonaTemplate | undefined {
  return PERSONA_TEMPLATES.find((p) => p.id === id);
}

/** 산업군 목록을 반환합니다. */
export function getIndustryList(): { id: string; industry: string; role: string }[] {
  return PERSONA_TEMPLATES.map(({ id, industry, role }) => ({ id, industry, role }));
}
